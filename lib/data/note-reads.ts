export function noteHelp(note: string): string {
  const key = note.toLowerCase();
  return HELP[key] ?? HELP_GENERIC[shapeFor(note)];
}

export function noteCalls(note: string): string {
  const key = note.toLowerCase();
  return CALLS[key] ?? CALLS_GENERIC[shapeFor(note)];
}

